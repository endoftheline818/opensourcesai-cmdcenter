test("catalog ordering is by fit then size — never by an invented score", async () => {
  const catalog = await load("data", "checker-models-snapshot.json");
  const graded = gradeCatalog(catalog.models, { vramGb: 12, systemRamGb: 32 });

  const order = { comfortable: 0, tight: 1, partial: 2, too_large: 3 };
  for (let i = 1; i < graded.length; i += 1) {
    const prev = order[graded[i - 1].fit];
    const cur = order[graded[i].fit];
    assert.ok(prev <= cur, "fit ordering must be monotonic");
    if (prev === cur) {
      assert.ok(
        (graded[i - 1].parametersBillions ?? 0) >= (graded[i].parametersBillions ?? 0),
        "within a fit tier, larger models come first",
      );
    }
  }
  assert.equal(graded.some((g) => "score" in g), false, "no composite score may be emitted");
});

// END-TO-END ACROSS THE REAL FIXTURES: the grading basis differs per platform,
// and getting it wrong is the whole class of bug Phase 0 existed to find.
test("each real machine grades against the right memory basis", async () => {
  const catalog = await load("data", "checker-models-snapshot.json");

  const windows = buildReport(await load("fixtures", "windows-rtx-4070-ti.json"));
  const winHw = resolveGradingHardware(windows);
  assert.equal(winHw.basis, "discrete-vram-nameplate");
  assert.equal(winHw.vramGb, 12, "must grade against nameplate 12, not raw 11.99");

  const linux = buildReport(await load("fixtures", "linux-rtx-3080.json"));
  const linuxHw = resolveGradingHardware(linux);
  assert.equal(linuxHw.basis, "discrete-vram-nameplate");
  assert.equal(linuxHw.vramGb, 10);

  const macos = buildReport(await load("fixtures", "macos-m1-8gb.json"));
  const macHw = resolveGradingHardware(macos);
  assert.equal(macHw.basis, "apple-unified-usable");
  assert.equal(macHw.vramGb, 6, "must grade against usable 6 GB, not the 8 GB sticker figure");

  // The consequence, stated as an assertion: the 8 GB Mac must be graded more
  // conservatively than a 10 GB discrete card, which is the entire reason the
  // usable-memory rule exists.
  const macFits = gradeCatalog(catalog.models, macHw).filter((m) => m.fit !== "too_large").length;
  const linuxFits = gradeCatalog(catalog.models, linuxHw).filter((m) => m.fit !== "too_large").length;
  assert.ok(macFits <= linuxFits, "an 8 GB Mac must not be told it runs more than a 10 GB card");
});

test("a machine with no GPU still grades, via RAM offload only", async () => {
  const catalog = await load("data", "checker-models-snapshot.json");
  const graded = gradeCatalog(catalog.models, { vramGb: 0, systemRamGb: 32 });
  assert.ok(graded.length > 0);
  assert.equal(graded.some((g) => g.fit === "comfortable"), false, "no GPU means nothing is comfortable");
  assert.ok(graded.some((g) => g.fit === "partial"), "small models should still be reachable via RAM");
});
